const FILE_BY_MODE = {
  production: 'src/environments/environment.production.ts',
  'production-design': 'src/environments/environment.production.ts',
  'development-local': 'src/environments/environment.development-local.ts',
  'development-remote': 'src/environments/environment.development-remote.ts',
  development: 'src/environments/environment.development-local.ts',
  local: 'src/environments/environment.development-local.ts',
  remote: 'src/environments/environment.development-remote.ts',
};

const mode = process.argv[2] ?? 'development-local';
const sourceRel = FILE_BY_MODE[mode] ?? FILE_BY_MODE['development-local'];
const defaultsKey =
  mode === 'development' || mode === 'local'
    ? 'development-local'
    : mode === 'remote'
      ? 'development-remote'
      : mode in DEFAULTS
        ? mode
        : 'development-local';
const defaults = DEFAULTS[defaultsKey];
const source = resolve(sourceRel);
const target = resolve('src/environments/environment.ts');

function boolEnv(name, fallback) {
  const raw = process.env[name];
  if (raw === undefined || raw === '') {
    return fallback;
  }
  return raw === '1' || raw.toLowerCase() === 'true';
}

function buildEnvironmentSource() {
  const production = boolEnv('PRODUCTION', defaults.production);
  const designMode = boolEnv('DESIGN_MODE', defaults.designMode);
  const apiUrl = process.env.API_URL || process.env.DEV_API_URL || defaults.apiUrl;
  const appUrl = process.env.APP_URL || process.env.DEV_APP_URL || defaults.appUrl;
  const authDomain =
    process.env.FIREBASE_AUTH_DOMAIN || FIREBASE_PUBLIC.authDomain;

  return `/** Auto-generated by scripts/prepare-environment.mjs (${defaultsKey}). */
export const environment = {
  production: ${production},
  designMode: ${designMode},
  apiUrl: ${JSON.stringify(apiUrl)},
  appUrl: ${JSON.stringify(appUrl)},
  firebaseConfig: {
    apiKey: ${JSON.stringify(FIREBASE_PUBLIC.apiKey)},
    authDomain: ${JSON.stringify(authDomain)},
    projectId: ${JSON.stringify(FIREBASE_PUBLIC.projectId)},
    storageBucket: ${JSON.stringify(FIREBASE_PUBLIC.storageBucket)},
    messagingSenderId: ${JSON.stringify(FIREBASE_PUBLIC.messagingSenderId)},
    appId: ${JSON.stringify(FIREBASE_PUBLIC.appId)},
    measurementId: ${JSON.stringify(FIREBASE_PUBLIC.measurementId)},
  },
};
`;
}

if (!existsSync(source)) {
  writeFileSync(source, buildEnvironmentSource(), 'utf8');
  console.log(`Generated missing ${sourceRel}`);
}

copyFileSync(source, target);
console.log(`Prepared ${target} from ${sourceRel}`);
